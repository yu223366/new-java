CREATE DATABASE IF NOT EXISTS `pokemon_game` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE `pokemon_game`;

-- ------------------------------------------------------------
-- 1. admin 管理员表（仅唯一超级管理员）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `admin` (
  `id` BIGINT PRIMARY KEY AUTO_INCREMENT,
  `username` VARCHAR(50) NOT NULL UNIQUE COMMENT '管理员账号',
  `password` VARCHAR(100) NOT NULL COMMENT '管理员密码',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='管理员';

INSERT IGNORE INTO `admin` (`username`, `password`) VALUES ('admin', '123456');

-- ------------------------------------------------------------
-- 2. player 玩家表（一枚玩家一行；state_json 存完整存档，换设备可恢复）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `player` (
  `id` BIGINT PRIMARY KEY AUTO_INCREMENT,
  `username` VARCHAR(50) NOT NULL UNIQUE COMMENT '玩家账号（与 t_user 对应）',
  `nickname` VARCHAR(50) DEFAULT NULL,
  `coins` INT NOT NULL DEFAULT 0 COMMENT '金币（币）',
  `starter_chosen` TINYINT NOT NULL DEFAULT 0 COMMENT '是否已选初始精灵',
  `banned` TINYINT NOT NULL DEFAULT 0 COMMENT '0正常 1封禁',
  `state_json` LONGTEXT COMMENT '完整游戏存档 JSON',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='玩家';

-- ------------------------------------------------------------
-- 3. player_pokemon 玩家精灵表
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `player_pokemon` (
  `id` BIGINT PRIMARY KEY AUTO_INCREMENT,
  `player_id` BIGINT NOT NULL,
  `uid` VARCHAR(40) NOT NULL COMMENT '存档内唯一 id',
  `number` VARCHAR(10) NOT NULL COMMENT '全国编号',
  `name` VARCHAR(50) NOT NULL,
  `level` INT NOT NULL DEFAULT 5,
  `hp` INT NOT NULL DEFAULT 0,
  `max_hp` INT NOT NULL DEFAULT 0,
  `atk` INT NOT NULL DEFAULT 0,
  `def` INT NOT NULL DEFAULT 0,
  `power` INT NOT NULL DEFAULT 0,
  `rarity` VARCHAR(20) DEFAULT '普通',
  `shiny` TINYINT NOT NULL DEFAULT 0,
  `evolved_at` DATETIME DEFAULT NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_player` (`player_id`),
  UNIQUE KEY `uk_player_uid` (`player_id`, `uid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='玩家精灵';

-- ------------------------------------------------------------
-- 4. player_bag 玩家背包（道具数量）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `player_bag` (
  `id` BIGINT PRIMARY KEY AUTO_INCREMENT,
  `player_id` BIGINT NOT NULL,
  `item_name` VARCHAR(50) NOT NULL,
  `qty` INT NOT NULL DEFAULT 0,
  UNIQUE KEY `uk_player_item` (`player_id`, `item_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='玩家背包';

